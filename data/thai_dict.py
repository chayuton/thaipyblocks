"""Build src/thai_dict.js: PyThaiNLP's default word list (the newmm dictionary), its Thai stopwords,
the syllable list (syllable_tokenize engine="dict") and the two TCC patterns (tcc_p for newmm, tcc for
subword_tokenize engine="tcc"), packed compactly so the in-browser tokenizers give the same words as
pythainlp.tokenize (newmm, longest, mm, syllables, tcc).

Packing: words are sorted and front-coded (shared-prefix length + suffix). Every character is
mapped to one printable ASCII character, so the dictionary costs ~1 byte per character."""
import json, os
import pythainlp
from pythainlp.corpus.common import thai_words, thai_stopwords
from pythainlp.corpus import thai_syllables
from pythainlp.tokenize import tcc_p, tcc

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'thai_dict.js')

# the Trie strips each word and ignores empty ones
words = sorted({w.strip() for w in thai_words()} - {''})
stop = sorted({w.strip() for w in thai_stopwords()} - {''})
syllables = sorted({w.strip() for w in thai_syllables()} - {''})

alpha = sorted({ch for w in words + stop for ch in w})
SAFE = [chr(c) for c in range(0x21, 0x7F) if chr(c) not in '"\\<>,`\'']
assert len(alpha) <= len(SAFE), (len(alpha), len(SAFE))
code = {ch: SAFE[i] for i, ch in enumerate(alpha)}
enc = lambda w: ''.join(code[ch] for ch in w)

B64 = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/'
def front_code(items, enc=enc):
    lens, sufs, prev = [], [], ''
    for w in items:
        k = 0
        while k < min(len(w), len(prev)) and w[k] == prev[k]:
            k += 1
        assert k < 64
        lens.append(B64[k]); sufs.append(enc(w[k:])); prev = w
    return lens, sufs
lens, sufs = front_code(words)
# the syllables use more characters than fit in one map, so they get their own
salpha = sorted({ch for w in syllables for ch in w})
assert len(salpha) <= len(SAFE), (len(salpha), len(SAFE))
scode = {ch: SAFE[i] for i, ch in enumerate(salpha)}
slens, ssufs = front_code(syllables, lambda w: ''.join(scode[ch] for ch in w))

# Python's `$` also matches before a final newline; JavaScript needs that spelled out
def js_regex(pattern):
    assert pattern.count('$') == pattern.count('|$)'), 'unexpected $ in TCC pattern'
    return pattern.replace('|$)', '|\\n?$)')
js_pattern = js_regex(tcc_p._PAT_TCC.pattern)
js_pattern_sub = js_regex(tcc._PAT_TCC.pattern)

data = {
    'version': pythainlp.__version__,
    'alpha': ''.join(alpha),
    'map': ''.join(SAFE[:len(alpha)]),
    'lens': ''.join(lens),
    'sufs': ','.join(sufs),
    'stop': ','.join(enc(w) for w in stop),
    'tcc': js_pattern,
    'salpha': ''.join(salpha),
    'smap': ''.join(SAFE[:len(salpha)]),
    'slens': ''.join(slens),
    'ssufs': ','.join(ssufs),
    'tcc_sub': js_pattern_sub,
}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* generated by data/thai_dict.py from PyThaiNLP %s (Apache-2.0): newmm word list, stopwords, syllables, TCC rules */\n' % pythainlp.__version__)
    # keep Thai readable but escape invisible characters such as U+FEFF
    text = json.dumps(data, ensure_ascii=False)
    text = ''.join(ch if ch.isprintable() or ch == ' ' else '\\u%04x' % ord(ch) for ch in text)
    f.write('PB.THAI_DICT = ' + text + ';\n')
print(f'{len(words)} words, {len(stop)} stopwords, {len(syllables)} syllables, {len(alpha)} chars -> {os.path.getsize(OUT) / 1024:.0f} KB')
