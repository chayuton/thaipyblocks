"""Build src/data.js with the embedded sample datasets (raw CSV text, byte-identical to the
files pd.read_csv() downloads) plus a compact encoding of sklearn's digits."""
import json, csv, io, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from thai_reviews_src import rows
from coffee_src import csv_text as coffee_csv
from orders_src import csv_text as orders_csv
from sklearn.datasets import load_digits

HERE = os.path.dirname(__file__)
OUT = os.path.join(HERE, "..", "src", "data.js")

def read(name):
    with open(os.path.join(HERE, name + ".csv"), encoding="utf-8") as f:
        return f.read()

# Thai reviews -> CSV (quoted, utf-8)
buf = io.StringIO()
w = csv.writer(buf, lineterminator="\n")
w.writerow(["text", "label", "category"])
for r in rows():
    w.writerow(r)
reviews_csv = buf.getvalue()
with open(os.path.join(HERE, "thai_reviews.csv"), "w", encoding="utf-8") as f:
    f.write(reviews_csv)

# messy coffee-shop members for the cleansing / normalization demo (also embedded in the Python code)
messy_csv = coffee_csv()
with open(os.path.join(HERE, "coffee_members.csv"), "w", encoding="utf-8") as f:
    f.write(messy_csv)

# messy online-shop orders (version 3.8): similar spellings and dates typed in many formats
shop_csv = orders_csv()
with open(os.path.join(HERE, "shop_orders.csv"), "w", encoding="utf-8") as f:
    f.write(shop_csv)

d = load_digits()
pix = "".join(chr(65 + int(v)) for v in d.data.astype(int).ravel())
tgt = "".join(str(int(t)) for t in d.target)
assert len(pix) == 1797 * 64

data = {
    "iris": read("iris"),
    "penguins": read("penguins"),
    "titanic": read("titanic"),
    "tips": read("tips"),
    "mpg": read("mpg"),
    "flights": read("flights"),
    "thai_reviews": reviews_csv,
    "coffee": messy_csv,
    "orders": shop_csv,
}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Embedded sample datasets (generated by data/prep.py). */\n")
    f.write("PB.RAW = " + json.dumps(data, ensure_ascii=False) + ";\n")
    f.write("PB.RAW.digits = " + json.dumps({"pixels": pix, "target": tgt}) + ";\n")
print("wrote", OUT, os.path.getsize(OUT), "bytes")
